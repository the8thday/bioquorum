const assert = require("node:assert/strict");
const { readFile } = require("node:fs/promises");

module.exports = async function materials(page) {
  page.setDefaultTimeout(8000);
  const button = (name) => page.getByRole("button", {name, exact:true});
  const file = (text) => ({name:"samples.csv", mimeType:"text/csv", buffer:Buffer.from(text)});
  const row = (version) => page.getByRole("article", {name:`samples.csv, version ${version}`});
  const download = async (version, expected) => {
    const pending = page.waitForEvent("download");
    await row(version).getByRole("link", {name:"Download file"}).click();
    const saved = await pending;
    assert.equal(saved.suggestedFilename(), "samples.csv");
    assert.equal(await readFile(await saved.path(),"utf8"), expected);
  };
  await button("Materials").click();
  await button("New research line").click();
  await page.getByLabel("Research line name").fill("Assay validation");
  await button("Create research line").click();
  await page.getByLabel("Research line", {exact:true}).getByRole("option", {name:"Assay validation",exact:true}).waitFor({state:"attached"});
  await button("Add current session").click();
  await page.getByText("Current session is in this research line.").waitFor();
  await button("Register material").click();
  await page.getByLabel("Material file", {exact:true}).setInputFiles(file("name\nA\n"));
  await page.getByLabel("Material type").selectOption("vendor_delivery");
  await page.getByLabel("Source description").fill("First vendor delivery");
  await button("Save material").click();
  await row(1).getByText("First vendor delivery").waitFor();
  await row(1).getByRole("button",{name:"Replace version"}).click();
  await page.getByLabel("Material file", {exact:true}).setInputFiles(file("name\nB\n"));
  await page.getByLabel("Source description").fill("Corrected vendor delivery");
  await page.getByLabel("Replacement reason").fill("Two labels corrected");
  await button("Save replacement").click();
  await row(2).getByText("Two labels corrected").waitFor();
  await row(1).getByText("Superseded", {exact:true}).waitFor();
  if (process.env.BQ_TEST_SCREENSHOT) await page.screenshot({path:process.env.BQ_TEST_SCREENSHOT});
  await download(1,"name\nA\n");
  await download(2,"name\nB\n");
  await row(2).getByRole("button",{name:"Withdraw version"}).click();
  await page.getByLabel("Withdrawal reason").fill("Batch recalled");
  await button("Confirm withdrawal").click();
  await row(2).getByText("Batch recalled").waitFor();
  await page.reload();
  await row(2).getByText("Withdrawn",{exact:true}).waitFor();
  await download(2,"name\nB\n");
  await button("New research line").click();
  await page.getByLabel("Research line name").fill("Review intake");
  await button("Create research line").click();
  await page.getByText("No materials registered in this research line.").waitFor();
  await button("Register material").click();
  await page.getByLabel("File source").selectOption("existing");
  await page.getByLabel("Existing upload").selectOption({label:"samples.csv · v2"});
  await page.getByLabel("Source description").fill("Reused from original intake");
  await button("Save material").click();
  await row(1).getByText("Reused from original intake").waitFor();
  await download(1,"name\nB\n");
  await button("Rename research line").click();
  await page.getByLabel("Research line name").fill("Independent review");
  await button("Save name").click();
  await page.getByRole("option",{name:"Independent review",exact:true}).waitFor({state:"attached"});
  await button("Close research line").click();
  await button("Confirm close").click();
  await page.getByRole("option",{name:"Independent review (closed)",exact:true}).waitFor({state:"attached"});
  assert.equal(await button("Register material").count(),0);
  assert.equal(await button("Replace version").count(),0);
  await download(1,"name\nB\n");
  await page.reload();
  await page.getByRole("option",{name:"Independent review (closed)",exact:true}).waitFor({state:"attached"});
  await page.getByLabel("Research line",{exact:true}).selectOption({label:"Assay validation"});
  await row(2).getByText("Batch recalled").waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.setViewportSize({width:1440,height:900});
  await button("New project").click();
  await page.getByLabel("Project name").fill("Independent project");
  await button("Create project").click();
  await page.waitForURL(/\/projects\/[A-Z0-9]+\//);
  await button("Materials").click();
  await page.getByText("No research lines in this project.").waitFor();
  assert.equal(await page.getByText("Assay validation").count(),0);
  await button("New research line").click();
  await page.getByLabel("Research line name").fill("Independent research");
  await button("Create research line").click();
  await button("Create a session for uploads").waitFor();
  await button("Create a session for uploads").click();
  await page.getByLabel("Session title").fill("Independent intake");
  await button("Continue").click();
  await page.getByRole("heading",{name:"Independent intake"}).waitFor();
  await button("Materials").click();
  await page.reload();
  await page.getByRole("option",{name:"Independent research",exact:true}).waitFor({state:"attached"});
  await page.goBack();
  await row(2).getByText("Batch recalled").waitFor();
  console.log("Verified material registration, same-name versions, withdrawal, downloads, reload and project isolation");
};
