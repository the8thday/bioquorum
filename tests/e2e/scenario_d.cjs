const path = require("node:path");
const assert = require("node:assert/strict");
const {readFile} = require("node:fs/promises");

module.exports = async function scenarioD(page) {
  page.setDefaultTimeout(15000);
  const csv = variant => readFile(path.join(__dirname,"../../evals/assets/v10-scenario-d",variant+".csv"));
  const button = name => page.getByRole("button",{name,exact:true});
  const row = v => page.getByRole("article",{name:`sample-labels.csv, version ${v}`});
  await button("3").click();
  const evidence = page.getByRole("dialog",{name:"control_mean"});
  await evidence.getByRole("link",{name:"sample-labels.csv · v1"}).waitFor();
  await evidence.getByRole("button",{name:"Close evidence"}).click();
  await button("Research lines").click();
  await page.getByText(/Control mean was 3(?:\.0)? AU/).first().waitFor();
  await button("Record decision").click();
  const edit = page.getByRole("dialog",{name:"Record decision"});
  await edit.getByText("Use a session answer as a draft").click();
  await edit.getByLabel("Session",{exact:true}).selectOption({label:"Original control analysis"});
  await edit.getByLabel("Recorded answer").selectOption({index:1});
  await edit.getByRole("button",{name:"Use answer as draft"}).click();
  assert.match(await edit.getByLabel("Decision text").inputValue(), /Control mean was 3/);
  await edit.getByLabel("Decision text").fill("Repeat the control measurement.");
  await edit.getByRole("checkbox",{name:/Control mean was/}).check();
  const savedRequest = page.waitForRequest(req=>req.method()==="POST" && req.url().endsWith("/decisions"));
  await edit.getByRole("button",{name:"Save decision"}).click();
  const submitted = (await savedRequest).postDataJSON();
  assert.ok(submitted.claim_revisions[submitted.claim_ids[0]], "submission must pin the exact reviewed claim version");
  await page.getByRole("article",{name:"Research decision"}).getByText("Repeat the control measurement.").waitFor();
  await button("Materials").click();
  await row(1).getByRole("button",{name:"Replace version"}).click();
  await page.getByLabel("Material file").setInputFiles({name:"sample-labels.csv",mimeType:"text/csv",
    buffer:await csv("corrected")});
  await page.getByLabel("Source description").fill("Corrected synthetic labels");
  await page.getByLabel("Replacement reason").fill("S1 and S2 group labels were swapped.");
  await button("Save replacement").click();
  await button("Original control analysis").click();
  await page.locator(".claim").getByText("Needs review",{exact:true}).waitFor();
  await button("Inbox").click();
  const inbox = page.getByRole("dialog",{name:"Inbox"});
  await inbox.getByRole("button",{name:/Control mean was/}).waitFor();
  await inbox.getByRole("link",{name:"Repeat the control measurement."}).click();
  await page.getByRole("article",{name:"Research decision"}).getByText("Needs review",{exact:true}).waitFor();
  await page.getByRole("heading",{name:"Pending review"}).locator("..").getByRole("button",{name:/Control mean/}).click();
  await page.getByRole("dialog",{name:"Source record"}).getByText("claim review flagged",{exact:true}).waitFor();
  await button("Close source record").click();
  await button("Materials").click();
  await row(1).getByRole("button",{name:"View impact"}).click();
  const impact = page.getByRole("dialog",{name:"Material impact"});
  await impact.getByText("Repeat the control measurement.").waitFor();
  await impact.getByText(/Estimated model cost/).waitFor();
  await impact.getByRole("button",{name:"Recompute with replacement"}).click();
  await impact.getByRole("cell",{name:"3 AU",exact:true}).waitFor();
  await impact.getByRole("cell",{name:"8 AU",exact:true}).waitFor();
  if (process.env.BQ_TEST_SCREENSHOT) await page.screenshot({path:process.env.BQ_TEST_SCREENSHOT});
  await impact.getByRole("button",{name:"Close impact"}).click();
  await button("Original control analysis").click();
  await page.getByRole("link",{name:"View corrected claim"}).click();
  await page.locator(".claim").getByRole("button",{name:"8",exact:true}).waitFor();
  await button("Research lines").click();
  const decision = page.getByRole("article",{name:"Research decision"});
  await decision.getByText("Needs review",{exact:true}).waitFor();
  await decision.getByText(/Control mean was 3(?:\.0)? AU/).waitFor();
  await page.getByText(/control_mean = 8(?:\.0)? AU/).first().waitFor();
  const download = page.waitForEvent("download");
  await page.getByRole("link",{name:"Download handoff summary"}).click();
  const data = JSON.parse(await readFile(await (await download).path(),"utf8"));
  assert.ok(data.decisions.some(d => d.needs_review));
  const zip = page.waitForEvent("download");
  await button("Download research bundle").click();
  assert.equal((await readFile(await (await zip).path())).readUInt32LE(),0x04034b50);
  await decision.getByRole("button",{name:"Revise decision"}).click();
  const revised=page.getByRole("dialog",{name:"Revise decision"});
  await revised.getByLabel("Decision text").fill("Reassess the corrected control measurement.");
  await revised.getByRole("checkbox",{name:/control_mean = 8/}).check();
  await revised.getByRole("button",{name:"Save decision"}).click();
  await decision.getByText("Reassess the corrected control measurement.").waitFor();
  assert.equal(await decision.getByText("Needs review",{exact:true}).count(),0);
  await button("Inbox").click();
  await inbox.getByText("No pending items.").waitFor();
  await inbox.getByRole("button",{name:"Close list"}).click();
  await decision.getByText("Previous decision versions").click();
  await decision.getByRole("button",{name:"Repeat the control measurement."}).waitFor();
  await button("New session in research line").click();
  await page.getByLabel("Session title").fill("Review corrected measurements");
  await button("Continue").click();
  await page.getByRole("heading",{name:"Review corrected measurements"}).waitFor();
  await button("Research lines").click();
  await page.getByRole("link",{name:"Review corrected measurements"}).waitFor();
  await button("Materials").click();
  await row(2).getByRole("button",{name:"Replace version"}).click();
  await page.getByLabel("Material file").setInputFiles({name:"sample-labels.csv",mimeType:"text/csv",
    buffer:await csv("renamed-column")});
  await page.getByLabel("Source description").fill("Delivery using the new column headings");
  await page.getByLabel("Replacement reason").fill("Group column renamed to arm.");
  await button("Save replacement").click();
  await row(2).getByRole("button",{name:"View impact"}).click();
  await impact.getByRole("button",{name:"Recompute with replacement"}).click();
  await impact.getByRole("heading",{name:"Recomputation · failed"}).waitFor();
  await impact.getByRole("button",{name:"Discuss a repair"}).click();
  await page.getByRole("heading",{name:"Recalculation with corrected material",exact:true}).waitFor();
  const draft=page.getByRole("textbox",{name:"Research question"});
  await draft.waitFor();
  assert.match(await draft.inputValue(), /Propose the smallest code or input change/);
  await button("Run research").click();
  const answer = page.locator(".answer").getByText("Validate the arm categories, then read the corrected arm column before recomputing.",{exact:true});
  await answer.waitFor();
  await page.reload();
  await answer.waitFor();
  console.log("Scenario D: real isolated computation, label correction, revised signal, fixed decision, handoff and bundle verified.");
};
